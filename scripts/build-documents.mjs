import { readFileSync, writeFileSync, mkdirSync, copyFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");
const researchDir = join(root, "..", "Understanding The Quranic Word Zakah");

const read = (name) => readFileSync(join(researchDir, name), "utf8");

const research = read("Final_Research_Zakah.md");
const detailed = read("Conclusion_Zakah.md");
const simple = read("Conclusion_Zakah_Simple.md");

const output = `// Generated by scripts/build-documents.mjs. Do not edit by hand.

export const researchMarkdown = ${JSON.stringify(research)};

export const conclusionDetailedMarkdown = ${JSON.stringify(detailed)};

export const conclusionSimpleMarkdown = ${JSON.stringify(simple)};
`;

writeFileSync(join(root, "src", "data", "documents.ts"), output, "utf8");

const publicResearch = join(root, "public", "research");
mkdirSync(publicResearch, { recursive: true });

writeFileSync(join(publicResearch, "Conclusion_Zakah.md"), detailed, "utf8");
writeFileSync(join(publicResearch, "Conclusion_Zakah_Simple.md"), simple, "utf8");

for (const name of [
  "1_Zakah_Verses.md",
  "2_Study_Order.md",
  "3_Study_Notes.md",
  "Verification_Zakah.md",
  "Final_Research_Zakah.md",
]) {
  copyFileSync(join(researchDir, name), join(publicResearch, name));
}

writeFileSync(join(root, "public", "research-zakah.md"), research, "utf8");

console.log("Wrote documents.ts and public research copies.");
console.log(`Detailed conclusion sections: ${(detailed.match(/^## \d+\./gm) ?? []).length}`);
